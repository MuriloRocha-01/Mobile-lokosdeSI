const assert = require('node:assert/strict')
const fs = require('node:fs')
const ts = require('typescript')
require.extensions['.ts'] = (module, path) => module._compile(ts.transpileModule(fs.readFileSync(path, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, path)
const { installmentPreview } = require('../src/utils/installments.ts')
assert.deepEqual(installmentPreview(100, '3', '', false), { count: 3, total: 100, interest: 0, first: 33.34, last: 33.33, payment: 0 })
assert.deepEqual(installmentPreview(1200, '12', '110,00', true), { count: 12, total: 1320, interest: 120, first: 110, last: 110, payment: 110 })
for (const count of ['0', '1', '121', '-2', '3.2', 'abc', '']) assert.equal(installmentPreview(100, count, '', false), null)
assert.equal(installmentPreview(0.01, '12', '', false), null)
assert.equal(installmentPreview(1200, '12', '90', true), null)
assert.equal(installmentPreview(Infinity, '12', '', false), null)
assert.equal(installmentPreview(1200, '12', '110.123', true), null)
console.log('Parcelas: arredondamento, juros e validação OK')
